/** Make HTML/CSS/JS self-contained in the Vercel Node module tree. Run npm run embed after front-end changes. */
import {readFile, writeFile} from 'node:fs/promises';
const names=['app.html','login.html','styles.css','app.js','favicon.svg'];
const result={};
for(const name of names)result[`web/${name}`]=(await readFile(new URL(`../web/${name}`,import.meta.url))).toString('base64');
const out=`// Generated by npm run embed; required for reliable Vercel deployments.\nexport const STATIC_ASSETS = ${JSON.stringify(result,null,2)};\n`;
await writeFile(new URL('../lib/web-assets.js',import.meta.url),out);
console.log('Embedded '+names.length+' protected UI assets.');
